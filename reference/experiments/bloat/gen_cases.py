#!/usr/bin/env python3
"""Generate the experiment's case files from the repo's own test files.

Side experiment: .claude/handoffs/SIDE_HANDOFF_bloat_calibration.md

Nothing in tests/ is modified. Each generated file is a copy of an existing test with exactly
one thing changed -- which padded system prompt it points at -- so that the ONLY difference
between two rounds is system-prompt length.

  python .claude/experiments/bloat/gen_cases.py

PRIMARY (describer_setting, 26 images, format checked by validate.py describer --role setting)
    one file per (arm, level): base twice for the noise floor, then 6 levels x 2 filler kinds
    x 2 positions = 26 runs. Case ids and 'same:' groups are kept verbatim, so validate.py's
    cross-case drift check still runs.

SECONDARY (fl2va composer, format checked by validate.py h3) -- image-bearing vs text-only.
    The handoff requires the composer's INPUT be held constant while only fl2va.txt is padded.
    That is achieved by putting every level into ONE file per arm: the 18 upstream cases
    (12 describer_frame + 6 fl2va_delta, both left unpadded) run once, and every composer case
    substitutes from that same result via {{p1_first}}-style tokens. So the chain genuinely
    runs, as the handoff asks, and its output is provably identical across all levels -- which
    re-running it once per level could not guarantee (L-DETERMINISM-IS-NOT-STABILITY notes a
    replayed CASE is not guaranteed identical, only a replayed RUN).

    The two arms differ in one key: the composer cases carry 'image' or do not. Frame and delta
    cases keep their images in both arms; they cannot work without them. Per the handoff each
    arm is compared only against ITS OWN unpadded baseline, never against the other in
    absolute terms.
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[2]
CASES = HERE / 'cases'

LEVELS = [3800, 3900, 4000, 4200, 4500, 5000]
PRIMARY_ARMS = ['a_end', 'b_end', 'a_mid', 'b_mid']

# Paths inside the generated case files are relative to the repo root, because run_tests.py is
# always invoked from there.
PADDED = '.claude/experiments/bloat/prompts'


def rel(p):
    return str(p).replace('\\', '/')


def primary():
    src = json.loads((ROOT / 'tests' / 'describer_setting.json').read_text(encoding='utf-8'))
    tags = []

    def write(tag, system_file):
        spec = json.loads(json.dumps(src))          # deep copy
        spec['_bloat_experiment'] = (
            'GENERATED by .claude/experiments/bloat/gen_cases.py -- do not edit by hand. '
            'Identical to tests/describer_setting.json except for defaults.system_file.')
        spec['_bloat_tag'] = tag
        spec['defaults']['system_file'] = system_file
        (CASES / f'primary__{tag}.json').write_text(
            json.dumps(spec, indent=2), encoding='utf-8')
        tags.append(tag)

    # Unpadded, twice. Session 11 found two identical rounds can be byte-identical; this is
    # where that gets confirmed, and it is this experiment's noise floor.
    write('base_1', 'prompts/describer_setting.txt')
    write('base_2', 'prompts/describer_setting.txt')

    for arm in PRIMARY_ARMS:
        for lvl in LEVELS:
            write(f'{arm}_{lvl}', f'{PADDED}/describer_setting__{arm}__{lvl}.txt')

    return tags


def secondary():
    src = json.loads((ROOT / 'tests' / 'cases_fl2va_full.json').read_text(encoding='utf-8'))
    upstream, composers = [], []
    for c in src['cases']:
        c = dict(c)
        c.pop('group', None)                        # banners complicate splitting the run file
        (composers if c['id'].endswith('_compose') else upstream).append(c)

    if len(upstream) != 18 or len(composers) != 6:
        raise SystemExit(f'ERROR: expected 18 upstream + 6 composer cases, got '
                         f'{len(upstream)} + {len(composers)} -- has the test file changed?')

    # base and base_2 give each arm its own noise floor; then the six padded levels.
    ladder = [('base', 'prompts/fl2va.txt'), ('base2', 'prompts/fl2va.txt')]
    ladder += [(str(l), f'{PADDED}/fl2va__a_end__{l}.txt') for l in LEVELS]

    tags = []
    for arm, keep_image in (('img', True), ('noimg', False)):
        cases = [dict(c) for c in upstream]
        for level, system_file in ladder:
            for c in composers:
                c = dict(c)
                c['id'] = f'c_{level}_{c["id"].split("_")[0]}'
                c['system_file'] = system_file
                if not keep_image:
                    c.pop('image', None)
                cases.append(c)
        spec = {
            '_bloat_experiment':
                'GENERATED by .claude/experiments/bloat/gen_cases.py -- do not edit by hand. '
                'Built from tests/cases_fl2va_full.json. The 18 upstream cases run ONCE and '
                'every composer level substitutes from that same result, so the composer input '
                'is identical at every padding level.',
            '_bloat_arm': arm,
            '_bloat_note': ('composer cases carry an image' if keep_image else
                            'composer cases have NO image -- the text-only arm. Frame and '
                            'delta cases keep theirs; they cannot work without them.'),
            'defaults': src['defaults'],
            'cases': cases,
        }
        (CASES / f'secondary__{arm}.json').write_text(
            json.dumps(spec, indent=2), encoding='utf-8')
        tags.append(arm)
        print(f'  secondary__{arm}.json  {len(cases)} cases '
              f'({len(upstream)} upstream + {len(ladder)} levels x {len(composers)})')
    return tags


def main():
    CASES.mkdir(exist_ok=True)
    missing = [m for m in json.loads((HERE / 'manifest.json').read_text(encoding='utf-8'))
               if not (HERE / 'prompts' / m['file']).exists()]
    if missing:
        raise SystemExit('ERROR: padded prompts missing -- run pad.py first')

    p = primary()
    print(f'  {len(p)} primary case files')
    s = secondary()

    (HERE / 'plan.json').write_text(json.dumps(
        {'primary_tags': p, 'secondary_arms': s, 'levels': LEVELS,
         'primary_arms': PRIMARY_ARMS}, indent=2), encoding='utf-8')
    print(f'\nwrote {len(p) + len(s)} case files to {rel(CASES.relative_to(ROOT))}/')
    return 0


if __name__ == '__main__':
    sys.exit(main())
