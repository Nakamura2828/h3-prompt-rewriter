#!/usr/bin/env python3
"""Generate the experiment's case files from the repo's own test files.

Side experiment: .claude/handoffs/SIDE_HANDOFF_bloat_calibration2.md

Nothing in tests/ is modified. Each generated file is a copy of an existing test with exactly one
thing changed -- which padded system prompt it points at -- so the ONLY difference between two
cells is the live/inert mix of the system prompt.

  python .claude/experiments/bloat2/gen_cases2.py

SETTING PROBE (describer_setting, 26 images, content metric = item counts, format = validate.py
    describer --role setting). One file per cell: L0 twice for the noise floor, then R and N at
    four live-rule levels each, plus the N-few cell at L3. Case ids and 'same:' groups are kept
    verbatim, so validate.py's cross-case drift check still runs.

FL2VA PROBE (fl2va composer, content metric = action coverage, format = validate.py h3).
    Round 1's single-invocation trick, copied: the 18 upstream cases (12 describer_frame + 6
    fl2va_delta, both left UNPADDED) run ONCE, and every level's composer cases substitute from
    that same result via {{p1_first}}-style tokens. So the chain genuinely runs and its output is
    provably identical across all nine cells -- which re-running it per cell could not guarantee
    (L-DETERMINISM-IS-NOT-STABILITY: a replayed CASE is not guaranteed identical, only a
    replayed RUN).
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[2]
assert ROOT.name == 'h3-prompt-rewriter' and (ROOT / '.git').is_dir(), \
    f'ROOT resolved to {ROOT} -- refusing to run outside the project'
CASES = HERE / 'cases'

PADDED = '.claude/experiments/bloat2/prompts'          # relative to ROOT: run_tests.py runs there

# (run tag, padded-prompt tag). Two tags share the L0 prompt: that pair IS the noise floor.
SETTING_CELLS = [
    ('s_L0', 'L0'), ('s_L0b', 'L0'),
    ('s_R2700', 'R2700'), ('s_R3100', 'R3100'), ('s_R3400', 'R3400'), ('s_R3800', 'R3800'),
    ('s_N2700', 'N2700'), ('s_N3100', 'N3100'), ('s_N3400', 'N3400'), ('s_N3800', 'N3800'),
    ('s_NF3400', 'NF3400'),
]

# (level label used in the case id, padded-prompt tag)
FL2VA_LEVELS = [
    ('L0', 'L0'), ('L0b', 'L0'),
    ('R3100', 'R3100'), ('R3400', 'R3400'), ('R3800', 'R3800'),
    ('N3100', 'N3100'), ('N3400', 'N3400'), ('N3800', 'N3800'),
    ('NF3400', 'NF3400'),
]

GEN = ('GENERATED by .claude/experiments/bloat2/gen_cases2.py -- do not edit by hand.')


def setting():
    src = json.loads((ROOT / 'tests' / 'describer_setting.json').read_text(encoding='utf-8'))
    if len(src['cases']) != 26:
        raise SystemExit(f'ERROR: expected 26 setting cases, got {len(src["cases"])} '
                         f'-- has tests/describer_setting.json changed?')
    tags = []
    for tag, prompt_tag in SETTING_CELLS:
        spec = json.loads(json.dumps(src))                      # deep copy
        spec['_bloat2'] = (GEN + ' Identical to tests/describer_setting.json except for '
                                 'defaults.system_file.')
        spec['_bloat2_tag'] = tag
        spec['defaults']['system_file'] = f'{PADDED}/describer_setting__{prompt_tag}.txt'
        (CASES / f'setting__{tag}.json').write_text(
            json.dumps(spec, indent=2), encoding='utf-8')
        tags.append(tag)
    print(f'  {len(tags)} setting case files, 26 images each')
    return tags


def fl2va():
    src = json.loads((ROOT / 'tests' / 'cases_fl2va_full.json').read_text(encoding='utf-8'))
    upstream, composers = [], []
    for c in src['cases']:
        c = dict(c)
        c.pop('group', None)                    # banners complicate splitting the run file
        (composers if c['id'].endswith('_compose') else upstream).append(c)
    if len(upstream) != 18 or len(composers) != 6:
        raise SystemExit(f'ERROR: expected 18 upstream + 6 composer cases, got '
                         f'{len(upstream)} + {len(composers)} -- has the test file changed?')

    cases = [dict(c) for c in upstream]
    for level, prompt_tag in FL2VA_LEVELS:
        for c in composers:
            c = dict(c)
            c['id'] = f'c_{level}_{c["id"].split("_")[0]}'      # c_R3100_p1
            c['system_file'] = f'{PADDED}/fl2va__{prompt_tag}.txt'
            cases.append(c)

    spec = {
        '_bloat2': GEN + ' Built from tests/cases_fl2va_full.json.',
        '_bloat2_note': ('The 18 upstream cases run ONCE with their UNPADDED prompts and every '
                         'composer level substitutes from that same result, so the composer '
                         'input is identical in every cell. Composer cases keep their image.'),
        'defaults': src['defaults'],
        'cases': cases,
    }
    (CASES / 'fl2va__f_img.json').write_text(json.dumps(spec, indent=2), encoding='utf-8')
    print(f'  fl2va__f_img.json  {len(cases)} cases '
          f'({len(upstream)} upstream + {len(FL2VA_LEVELS)} levels x {len(composers)})')
    return ['f_img']


def main():
    CASES.mkdir(exist_ok=True)
    manifest = json.loads((HERE / 'manifest.json').read_text(encoding='utf-8'))
    missing = [m['file'] for m in manifest if not (HERE / 'prompts' / m['file']).exists()]
    if missing:
        raise SystemExit(f'ERROR: padded prompts missing -- run pad2.py first: {missing}')

    s = setting()
    f = fl2va()
    (HERE / 'plan.json').write_text(json.dumps(
        {'setting_tags': s, 'fl2va_tags': f,
         'setting_cells': SETTING_CELLS, 'fl2va_levels': FL2VA_LEVELS}, indent=2),
        encoding='utf-8')
    print(f'\nwrote {len(s) + len(f)} case files to '
          f'{str(CASES.relative_to(ROOT)).replace(chr(92), "/")}/')
    return 0


if __name__ == '__main__':
    sys.exit(main())
